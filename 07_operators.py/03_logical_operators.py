# Logical Operators
c = True
d = False
print(c and d)
print(d and c)
print(c and c)
print(d and d)
# and = true and true is true and else is false.

print("# for and operator")
print(True and False)
print(True and True)
print(False and False)
print(False and True)
# both true return true and else false.

print('## for or operator')
print(True or False)
print(True or True)
print(False or False)
print(False or True)
#both false returns the false else the true. 

print("### for not operator")
print(not(True))
print(not(False))
# Typecasting means converting 1 datatype to another.

a = 55

b = "69"

d = 456

print(a)
print(type(a))

print(b)
print(type(b)) # the output will be in str

# convert the str into float

c = int(b)
print(c)
print(type(c)) # and now the output will be in str.

# there can be int that shall convert it into the str.

e = str(d)
print(e)
print(type(e))

